// Rebuilds everything that is generated from data.js:
//   site/data.js, the site pages, career-bank.md, build/portfolio.html -> Kritan_Duwal_Portfolio.pdf
//   node build/build.js
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const D = require(path.join(ROOT, 'data.js'));
const P = D.person;
// Used in the PDF only. Kept out of data.js because data.js is published with the site.
const PHONE = '+1 662 694 9788';
// Set this once the site is hosted; the PDF's "Listen" links will then point at it.
const SITE_URL = 'https://kritanduwal.com';

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const byId = Object.fromEntries(D.projects.map(p => [p.id, p]));
const catLabel = Object.fromEntries(D.categories.map(c => [c.id, c.label]));

// ---------- site assets ----------
// The published copy holds only what the pages use: no hidden projects, local file paths or career-bank material.
const siteData = {
  person: P, categories: D.categories, pages: D.pages,
  projects: D.projects.filter(p => p.site !== false).map(({ evidence, caveat, onResume, ...rest }) => rest),
  experience: D.experience.map(x => ({ title: x.title, org: x.org, dates: x.dates, bullets: x.bullets.filter(b => !b.alt).map(b => ({ text: b.text })) })),
  skillBank: D.skillBank,
};
fs.writeFileSync(path.join(ROOT, 'site', 'data.js'), '// Generated by build/build.js from ../data.js. Do not edit.\nwindow.PORTFOLIO = ' + JSON.stringify(siteData) + ';\n');

// ---------- site pages (one HTML shell per entry in data.pages; app.js fills them in) ----------
const DESCRIPTION = 'Portfolio of Kritan Duwal: spatial audio research, DSP and plugins, acoustic measurement, recording, mixing and mastering. Listen to the work.';
for (const pg of D.pages) {
  const nav = D.pages.filter(x => x.id !== 'home').map(x =>
    '<a href="' + x.file + '"' + (x.id === pg.id ? ' aria-current="page"' : '') + '>' + esc(x.nav) + '</a>').join('\n    ');
  fs.writeFileSync(path.join(ROOT, 'site', pg.file), [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<title>' + esc(pg.title) + '</title>',
    '<meta name="description" content="' + esc(pg.intro || DESCRIPTION) + '">',
    '<link rel="stylesheet" href="style.css">',
    '</head>',
    '<body>',
    '<!-- Generated by build/build.js from data.js. Edit those, not this file. -->',
    '<a class="skip" href="#main">Skip to content</a>',
    '<header class="top">',
    '  <a class="brand" href="index.html">Kritan Duwal</a>',
    '  <nav aria-label="Pages">',
    '    ' + nav,
    '  </nav>',
    '</header>',
    '<main id="main" data-page="' + pg.id + '"></main>',
    '<footer>',
    '  <p>Recordings are excerpts shared for portfolio review. Performances, compositions and source multitracks belong to their respective artists and owners.</p>',
    '  <p><a href="mailto:' + P.email + '">' + P.email + '</a> · <a href="' + P.links.linkedin + '">LinkedIn</a> · <a href="' + P.links.github + '">GitHub</a></p>',
    '</footer>',
    '<script src="data.js"></script>',
    '<script src="audio-meta.js"></script>',
    ...(pg.id === 'dsp' ? ['<script src="hybrid-pan-mix.js"></script>'] : []),
    '<script src="app.js"></script>',
    '</body>',
    '</html>',
    '',
  ].join('\n'));
}

// ---------- career-bank.md ----------
const win = p => p.replace(/\//g, '\\');
const md = [];
md.push('# Career Bank - ' + P.name, '',
  'Generated from `data.js` by `build/build.js`. Do not edit this file; edit `data.js` and rebuild.',
  'Interactive version: `career-bank.html`. Use this file to look up where the evidence for a claim lives, or to assemble a resume for a given role.', '',
  '## Links', '', ...Object.entries(P.links).map(([k, v]) => '- ' + k + ': ' + v), '',
  '## Education', '', ...P.education.map(e => '- **' + e.degree + '**, ' + e.school + ' (' + e.dates + '). Coursework: ' + e.courses), '',
  '## Target roles', '');
D.targets.forEach(t => md.push('### ' + t.label + ' (`' + t.id + '`)', '', '**Summary:** ' + t.summary, '',
  '**Lead with:** ' + t.lead.map(id => byId[id].short).join(' > '), '',
  '**Skills order:**', ...t.skills.map(s => '- ' + s), '', '**Keywords:** ' + t.keywords.join(', '), ''));
md.push('## Work experience bullets', '', 'Tags in brackets are the target roles each bullet suits. `extra` = not on the current resume.', '');
D.experience.forEach(x => md.push('### ' + x.title + ', ' + x.org + ' (' + x.dates + ')', '',
  ...x.bullets.map(b => '- ' + b.text + ' [' + b.t.join(', ') + (b.alt ? '; extra' : '') + ']'), ''));
md.push('## Project bullets', '');
D.projectBullets.forEach(x => md.push('### ' + x.heading + ' (' + x.dates + ')', '',
  ...x.bullets.map(b => '- ' + b.text + ' [' + b.t.join(', ') + (b.alt ? '; extra' : '') + ']'), ''));
md.push('## Skill bank', '', ...D.skillBank.map(s => '- **' + s.group + ':** ' + s.items), '', '## Project index', '');
D.projects.forEach(p => md.push('### ' + p.short + ' (`' + p.id + '`)', '',
  '- Area: ' + catLabel[p.cat] + ' | Period: ' + p.period + ' | On current resume: ' + (p.onResume ? 'yes' : 'no'),
  '- Role: ' + p.role, '- Summary: ' + p.summary, ...p.points.map(t => '- ' + t),
  '- Stack: ' + p.stack.join(', '),
  ...(p.links || []).map(l => '- Link: ' + l.label + ' - ' + l.href),
  ...(p.caveat ? ['- Check before using: ' + p.caveat] : []),
  '- Evidence on disk:', ...p.evidence.map(e => '  - `' + win(e) + '`'), ''));
md.push('## Archive: other material on disk', '', ...D.archive.map(a => '- ' + a.what + ': `' + win(a.path) + '`'), '');
fs.writeFileSync(path.join(ROOT, 'career-bank.md'), md.join('\n'));

// ---------- portfolio PDF ----------
const pageFile = id => D.pages.find(pg => pg.cats && pg.cats.includes(byId[id].cat)).file;
const listen = id => SITE_URL ? SITE_URL.replace(/\/$/, '') + '/' + pageFile(id) + '#' + id : P.links.drive;
const order = ['aural-heritage', 'aes-paper', 'hybrid-pan', 'matlab-dsp', 'ir-modeling', 'ap-measurement', 'samba-funk', 'mix-techniques', 'mastering', 'gen-audio', 'first-command'];

function projectHtml(id, n) {
  const p = byId[id], img = (p.images || [])[0];
  const links = [...(p.links || []).map(l => '<a href="' + esc(l.href) + '">' + esc(l.label) + '</a>')];
  if (p.audio && p.audio.some(s => s.clips)) links.push('<a href="' + esc(listen(id)) + '">Listen to the audio</a>');
  return `<article class="proj${img ? '' : ' noimg'}">
  <div class="txt">
    <div class="meta"><span class="num">${String(n).padStart(2, '0')}</span>${esc(p.kind || catLabel[p.cat])} · ${esc(p.period)}</div>
    <h2>${esc(p.title)}</h2>
    <p class="role">${esc(p.role)}</p>
    <p class="sum">${esc(p.summary)}</p>
    <ul>${p.points.map(t => '<li>' + esc(t) + '</li>').join('')}</ul>
    ${p.extra ? '<p class="extra">' + esc(p.extra) + '</p>' : ''}
    <p class="tags">${p.stack.map(s => '<span>' + esc(s) + '</span>').join('')}</p>
    ${links.length ? '<p class="links">' + links.join('') + '</p>' : ''}
  </div>
  ${img ? '<figure><img src="../site/img/' + img.src + '" alt=""><figcaption>' + esc(img.cap) + '</figcaption></figure>' : ''}
</article>`;
}

